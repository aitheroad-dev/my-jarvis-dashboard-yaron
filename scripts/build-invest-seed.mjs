#!/usr/bin/env node
/**
 * build-invest-seed.mjs — generate sql/d1/016_invest_seed.sql from the Advisor
 * Corpus pipeline output (How to Invest My Money project).
 *
 * Reads the PoC/TestRuns artifacts (transcript.txt / summary.md / claims.md per
 * video), RE-RUNS the deterministic quote validation (normalize both sides,
 * exact substring — never fuzzy), and emits an idempotent re-seed (DELETE+INSERT).
 * This script is the prototype of the future `advisor-corpus push` verb.
 *
 * Usage: node scripts/build-invest-seed.mjs
 * Then:  script -q /dev/null node ./node_modules/wrangler/bin/wrangler.js \
 *          d1 execute mjd-yaron-db --remote --yes --file=sql/d1/016_invest_seed.sql
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { homedir } from "node:os";

const CORPUS = join(
  homedir(),
  ".claude/PAI/USER/PROJECTS/HOW_TO_INVEST_MY_MONEY/AdvisorCorpus/TestRuns",
);

const CHANNELS = [
  {
    id: "AndreiJikh",
    name: "Andrei Jikh",
    handle: "@AndreiJikh",
    style: "Macro narrative / entertainment",
    jurisdiction: "global",
    on_roster: 0,
    notes:
      "Off-roster stress test. Headline-driven macro stories; stance data shows predictions are rarely owned — most are attributed to others or framed as hypotheticals.",
  },
  {
    id: "BenFelixCSI",
    name: "Ben Felix",
    handle: "@BenFelixCSI",
    style: "Evidence-based",
    jurisdiction: "global",
    on_roster: 1,
    notes:
      "Anchor channel — cites academic research, scripted delivery (cleanest transcripts). Top-6 roster.",
  },
  {
    id: "AngeloColomboFi",
    name: "Angelo Colombo",
    handle: "@AngeloColomboFi",
    style: "Educational, EU-focused",
    jurisdiction: "EU",
    on_roster: 1,
    notes:
      "Highest EU relevance on the roster: UCITS ETFs, EU brokers, FIRE in Europe. Top-6 roster.",
  },
];

// dir per video: where its transcript/summary/claims artifacts live
const VIDEOS = [
  { id: "Z_xvkbGWauU", channel_id: "AndreiJikh", dir: "2026-07-10-jikh" },
  { id: "siazPdsZHuI", channel_id: "AndreiJikh", dir: "2026-07-10-jikh" },
  { id: "Uwl3-jBNEd4", channel_id: "BenFelixCSI", dir: "2026-07-10-roster" },
  { id: "-nPon8Ad_Ug", channel_id: "BenFelixCSI", dir: "2026-07-10-roster" },
  { id: "MeY18uWJrso", channel_id: "AngeloColomboFi", dir: "2026-07-10-roster" },
  { id: "HCwoH-W25bQ", channel_id: "AngeloColomboFi", dir: "2026-07-10-roster" },
];

const TYPES = new Set(["fact", "recommendation", "prediction", "opinion", "numeric", "warning"]);
const STANCES = new Set(["asserts", "reports_other", "hypothetical"]);

const norm = (s) =>
  s
    .toLowerCase()
    .replace(/[‘’“”"]/g, "")
    .replace(/\s+/g, " ")
    .trim();

const q = (s) => (s == null ? "NULL" : `'${String(s).replace(/'/g, "''")}'`);

// videos-meta.psv: id|views|duration|upload_date|channel|title
const meta = {};
for (const line of readFileSync(join(CORPUS, "videos-meta.psv"), "utf8").trim().split("\n")) {
  const [id, views, duration, upload, , ...title] = line.split("|");
  meta[id] = {
    views: Number(views),
    duration_s: Number(duration),
    upload_date: `${upload.slice(0, 4)}-${upload.slice(4, 6)}-${upload.slice(6, 8)}`,
    title: title.join("|"),
  };
}

const stmts = [
  "-- GENERATED by scripts/build-invest-seed.mjs — do not hand-edit. Re-run the script instead.",
  "DELETE FROM invest_claims;",
  "DELETE FROM invest_videos;",
  "DELETE FROM invest_channels;",
];

for (const c of CHANNELS) {
  stmts.push(
    `INSERT INTO invest_channels (id, name, handle, style, jurisdiction, on_roster, notes) VALUES (${q(c.id)}, ${q(c.name)}, ${q(c.handle)}, ${q(c.style)}, ${q(c.jurisdiction)}, ${c.on_roster}, ${q(c.notes)});`,
  );
}

let totalClaims = 0;
let totalValidated = 0;

for (const v of VIDEOS) {
  const base = join(CORPUS, v.dir, v.id);
  if (!existsSync(`${base}.claims.md`)) {
    console.error(`MISSING artifacts for ${v.id} — aborting (a failed input is its own state).`);
    process.exit(1);
  }
  const transcript = norm(readFileSync(`${base}.transcript.txt`, "utf8"));
  const words = readFileSync(`${base}.transcript.txt`, "utf8").trim().split(/\s+/).length;
  const summary = readFileSync(`${base}.summary.md`, "utf8").trim();
  const m = meta[v.id];

  const rows = readFileSync(`${base}.claims.md`, "utf8")
    .split("\n")
    .filter((l) => l.startsWith("|") && !l.includes("---") && !/\|\s*claim\s*\|/i.test(l));

  const claims = [];
  for (const r of rows) {
    const c = r.split("|").map((x) => x.trim());
    // cells: [ , claim, type, stance, quote, jurisdiction, ]
    if (c.length < 6) continue;
    const type = TYPES.has(c[2]) ? c[2] : "opinion";
    const stance = STANCES.has(c[3]) ? c[3] : "asserts";
    const quote = (c[4] || "").replace(/^"|"$/g, "");
    const jurisdiction = ["global", "US", "EU", "NL"].includes(c[5]) ? c[5] : "global";
    const validated = transcript.includes(norm(quote)) ? 1 : 0;
    claims.push({ claim: c[1], type, stance, quote, jurisdiction, validated });
  }

  const validated = claims.filter((c) => c.validated).length;
  totalClaims += claims.length;
  totalValidated += validated;

  stmts.push(
    `INSERT INTO invest_videos (id, channel_id, title, url, views, duration_s, upload_date, words, transcript_source, summary_md, claims_total, claims_validated, claims_quarantined, processed_at) VALUES (${q(v.id)}, ${q(v.channel_id)}, ${q(m.title)}, ${q(`https://www.youtube.com/watch?v=${v.id}`)}, ${m.views}, ${m.duration_s}, ${q(m.upload_date)}, ${words}, 'auto', ${q(summary)}, ${claims.length}, ${validated}, ${claims.length - validated}, ${q(new Date().toISOString())});`,
  );
  for (const c of claims) {
    stmts.push(
      `INSERT INTO invest_claims (video_id, claim, type, stance, quote, jurisdiction, validated) VALUES (${q(v.id)}, ${q(c.claim)}, ${q(c.type)}, ${q(c.stance)}, ${q(c.quote)}, ${q(c.jurisdiction)}, ${c.validated});`,
    );
  }
  console.log(`${v.id} (${v.channel_id}): ${claims.length} claims, ${validated} validated`);
}

writeFileSync(join(process.cwd(), "sql/d1/016_invest_seed.sql"), stmts.join("\n") + "\n");
console.log(`\nWrote sql/d1/016_invest_seed.sql — ${totalClaims} claims (${totalValidated} validated), 6 videos, 3 channels.`);
